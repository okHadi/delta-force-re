int select_voice(const std::array<MixVoice, kMixVoiceCount>& live,
                 const std::array<MixVoice, kMixVoiceCount>& pending,
                 int volume) {
    // FUN_004b4f5e first pass: live slot free of both flags and no pending.
    for (std::size_t index = 0; index < kMixVoiceCount; ++index) {
        if (live[index].stop == 0 && live[index].active == 0 && pending[index].active == 0) {
            return static_cast<int>(index);
        }
    }
    // Second pass: use the first eligible live slot with a lower volume.
    for (std::size_t index = 0; index < kMixVoiceCount; ++index) {
        if (live[index].stop == 0 && pending[index].active == 0 && volume > live[index].volume) {
            return static_cast<int>(index);
        }
    }
    return -1;
}

MixVoice start_voice(const SampleRecord& record, std::uint32_t pcm_address,
                     int pan, int volume, int master_volume,
                     std::uint32_t rate_scale) {
    MixVoice voice;
    voice.end = pcm_address + record.length;
    voice.length = record.length;
    voice.step = record.step;
    // 0x4b4fd0 path: position starts one byte short of the end, 1/1024 units.
    voice.position = as_signed((0u - (record.length - 1u)) << kMixPositionShift);
    const std::uint32_t scale = rate_scale == 0 ? 0x10000u : rate_scale;
    const std::int64_t product =
        static_cast<std::int64_t>(static_cast<std::int32_t>(scale)) *
        static_cast<std::int64_t>(static_cast<std::int32_t>(record.step));
    voice.frequency = static_cast<std::uint32_t>(
        static_cast<std::int64_t>(product >> 32) >> 2);
    voice.pan = pan;
    voice.volume = volume;
    voice.sample_volume = static_cast<std::uint8_t>(record.volume & 0xffu);
    const StereoGain gain = compute_voice_gain(pan, volume, master_volume,
                                               voice.sample_volume);
    voice.right_gain = gain.right;
    voice.left_gain = gain.left;
    voice.active = 1;
    voice.stop = 0;
    voice.dirty = 0;
    return voice;
}

VoiceStep advance_voice(MixVoice& voice) {
    VoiceStep step;
    const std::uint32_t biased =
        static_cast<std::uint32_t>(voice.position) + kMixPositionBias;
    step.ended = biased < static_cast<std::uint32_t>(voice.position);
    if (step.ended) {
        // 0x4a3655 taken: position is kept and no sample is fetched.
        step.position = voice.position;
        return step;
    }
    voice.position = as_signed(biased);
    step.position = voice.position;
    step.index = arithmetic_shift(step.position, kMixPositionShift);
    step.address = static_cast<std::uint32_t>(step.index) - kMixFetchBias;
    return step;
}

std::int32_t sample_value(std::uint8_t byte) {
    return static_cast<std::int32_t>(byte) - 0x80;
}

std::int32_t accumulate(std::int32_t accumulator, std::uint8_t byte,
                        std::int32_t gain) {
    const std::uint32_t product =
        static_cast<std::uint32_t>(sample_value(byte)) *
        static_cast<std::uint32_t>(gain);
    return as_signed(static_cast<std::uint32_t>(accumulator) + product);
}

GainKernel gain_kernel(std::int32_t gain) {
    GainKernel kernel;
    const std::int64_t shift_at = static_cast<std::int64_t>(gain) + kWindowBase;
    if (shift_at < 0 || shift_at >= static_cast<std::int64_t>(kShiftWindow.size())) {
        kernel.in_window = false;
        return kernel;
    }
    kernel.shift = kShiftWindow[static_cast<std::size_t>(shift_at)];
    const std::uint32_t shifted = static_cast<std::uint32_t>(gain)
        << (kernel.shift & 31u);
    kernel.index = arithmetic_shift(as_signed(shifted), 3);
    const std::int64_t bytes_at = static_cast<std::int64_t>(kernel.index) * 8 + kKernelWindowBase;
    if (bytes_at < 0 ||
        bytes_at + 8 > static_cast<std::int64_t>(kKernelWindow.size())) {
        kernel.in_window = false;
        return kernel;
    }
    for (std::size_t at = 0; at < kernel.bytes.size(); ++at) {
        kernel.bytes[at] = kKernelWindow[static_cast<std::size_t>(bytes_at) + at];
    }
    return kernel;
}

