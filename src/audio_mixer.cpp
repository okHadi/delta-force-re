inline constexpr std::size_t kKernelWindowBase=0x100;

inline constexpr std::size_t kWindowBase = 0x80;

inline std::int32_t as_signed(std::uint32_t value) {
    return value < 0x80000000u ? static_cast<std::int32_t>(value)
                               : static_cast<std::int32_t>(value - 0x80000000u) - 0x7fffffff - 1;
}

inline std::int32_t arithmetic_shift(std::int32_t value, int count) {
    const std::int64_t divisor = static_cast<std::int64_t>(1) << count;
    const std::int64_t wide = value;
    if (wide >= 0) {
        return static_cast<std::int32_t>(wide / divisor);
    }
    return static_cast<std::int32_t>(-((-wide + divisor - 1) / divisor));
}

